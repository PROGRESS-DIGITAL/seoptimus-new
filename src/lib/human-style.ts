export type LengthTarget = { min: number; max: number | null };

/**
 * Объём из полей формы: «Средне (1000–1500 знаков)», «4000 знаков», «до 160 знаков»,
 * «2000+ знаков». Для рерайта и правки: не короче исходного текста.
 */
export function lengthTarget(input: Record<string, string>): LengthTarget | null {
  if (input.source?.trim()) {
    const n = input.source.trim().length;
    return { min: Math.round(n * 0.9), max: Math.round(n * 1.25) };
  }
  // Поле «Количество символов» со значением вида «1000»
  if (/^\d{3,5}$/.test(input.length?.trim() ?? "")) {
    const n = Number(input.length.trim());
    return { min: Math.round(n * 0.9), max: Math.round(n * 1.15) };
  }
  for (const raw of Object.values(input)) {
    // «3 тыс. символов», «2,5 тысячи знаков» → «3000 знаков»
    const v = raw
      .replace(/(\d+(?:[.,]\d+)?)\s*(?:тыс\.?|тысяч[иа]?|k)(?=\s)/gi, (_, n: string) => String(Math.round(Number(n.replace(",", ".")) * 1000)))
      .replace(/символ/gi, "знак");
    if (!/знак/i.test(v)) continue;
    const range = v.match(/(\d[\d\s]*)\s*[–-]\s*(\d[\d\s]*)\s*знак/i);
    if (range) return { min: num(range[1]), max: num(range[2]) };
    const upTo = v.match(/до\s*(\d[\d\s]*)\s*знак/i);
    if (upTo) return { min: 0, max: num(upTo[1]) };
    const plus = v.match(/(\d[\d\s]*)\s*\+\s*знак/i);
    if (plus) return { min: num(plus[1]), max: null };
    const exact = v.match(/(\d[\d\s]*)\s*знак/i);
    if (exact) {
      const n = num(exact[1]);
      return { min: Math.round(n * 0.9), max: Math.round(n * 1.15) };
    }
  }
  return null;
}
const num = (s: string) => Number(s.replace(/\s/g, ""));

export function lengthRule(t: LengthTarget | null, rewrite: boolean) {
  if (!t) return "";
  if (rewrite)
    return `\n\nОбъём: исходный текст около ${Math.round(t.min / 0.9)} знаков. Результат должен быть не короче ${t.min} знаков: сохрани все абзацы, факты и мысли, ничего не выбрасывай и не сокращай.`;
  if (!t.min && t.max) return `\n\nОбъём: не больше ${t.max} знаков с пробелами.`;
  if (t.max) return `\n\nОбъём: от ${t.min} до ${t.max} знаков с пробелами. Не короче ${t.min}.`;
  return `\n\nОбъём: не меньше ${t.min} знаков с пробелами, пиши подробно.`;
}

/** Убирает «хвосты нейросети»: вступления, предложения помочь ещё, markdown */
export function cleanAiTails(text: string) {
  let t = text.trim();
  // Вступление вроде «Конечно! Вот статья о …:»
  t = t.replace(/^(конечно|разумеется|отлично|хорошо|вот)[^\n]{0,120}:\s*\n+/i, "");
  // Финальные предложения помощи
  const lines = t.split("\n");
  while (
    lines.length > 1 &&
    /^(если (нужно|хотите|потребуется|понадобится)|надеюсь|могу также|могу (ещё|еще)|дайте знать|готов помочь|обращайтесь)/i.test(
      lines[lines.length - 1].trim(),
    )
  )
    lines.pop();
  t = lines.join("\n").trim();
  // Markdown и заготовки в скобках
  return dropPlaceholders(toPlainText(t));
}
