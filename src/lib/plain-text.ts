/**
 * Убирает markdown из ответа нейросети, чтобы в выдаче не было звёздочек, решёток и т.п.
 * Работает и на сервере (сохраняем чистый текст), и в браузере (пока текст печатается).
 * Блоки кода в тройных кавычках не трогаем.
 */
export function toPlainText(text: string, opts: { bullet?: string } = {}) {
  const bullet = opts.bullet ?? "— ";
  return text
    .split(/(```[\s\S]*?(?:```|$))/g)
    .map((part, i) => (i % 2 === 1 ? part : cleanPart(part, bullet)))
    .join("")
    .replace(/\n{3,}/g, "\n\n");
}

function cleanPart(t: string, bullet: string) {
  return (
    t
      // **жирный**, __жирный__, ***оба***
      .replace(/\*{2,3}([^*\n]+?)\*{2,3}/g, "$1")
      .replace(/__([^_\n]+?)__/g, "$1")
      // *курсив* (не трогаем «2 * 3» и маркеры списка)
      .replace(/(^|[^\w*])\*(?!\s)([^*\n]+?)(?<!\s)\*(?!\w)/g, "$1$2")
      // недописанные звёздочки, пока текст печатается
      .replace(/\*\*/g, "")
      // заголовки
      .replace(/^#{1,6}\s+/gm, "")
      // `код` в строке
      .replace(/`([^`\n]+)`/g, "$1")
      // [текст](ссылка) → текст (ссылка)
      .replace(/\[([^\]\n]+)\]\((https?:\/\/[^)\s]+)\)/g, "$1 ($2)")
      // > цитаты
      .replace(/^>\s?/gm, "")
      // разделители ---
      .replace(/^\s*([-*_])\1{2,}\s*$/gm, "")
      // маркеры списков
      .replace(/^(\s*)[-*•]\s+(?=\S)/gm, `$1${bullet}`)
  );
}

/**
 * Заготовки вида «до [укажите расстояние] м» не должны попадать в текст.
 * Строки-пункты с такими заготовками убираем целиком, а фразу «замените значения в скобках» вырезаем.
 */
export function dropPlaceholders(text: string) {
  const ph = /\[(укажите|вставьте|впишите|добавьте|введите|ваш|ваше|ваша|ваши|название|имя|номер|адрес|телефон|ссылка|дата|цена|сумма|город|x+|\.\.\.)[^\]\n]*\]/i;
  return text
    .split("\n")
    .filter((line) => !(ph.test(line) && /^\s*(—|-|•|\d+[.)])?\s*[^:\n]{0,60}:/.test(line)))
    .join("\n")
    .replace(/[^.!?\n]*(замените|подставьте|укажите)[^.!?\n]*(в (квадратных )?скобках|на (реальные|свои|актуальные))[^.!?\n]*[.!?]?/gi, "")
    .replace(/[ \t]+\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}
